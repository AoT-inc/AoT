"""Matter Input(MATTER_NODE)·Output(MATTER_ON_OFF) 모듈과 온보딩 청사진 검사.

실제 Matter 서버·DB 없이 가짜 클라이언트로 돈다. 지키는 것:
  - Input: 노드가 응답할 때만 값을 쓴다(연결이 끊기거나 노드가 unavailable 이면
    캐시 값을 새 값처럼 다시 쓰지 않는다). 변화 이벤트는 해당 채널만, 변환을
    거쳐 즉시 쓴다. null 은 쓰지 않는다.
  - Output: 명령은 device_command On/Off 로 나가고, 확정은 장치의 OnOff 보고가
    한다. 서버 오류는 (1, 메시지)로 돌려주고 낙관적 상태를 남기지 않는다.
    상태를 모르는 채널은 is_on() 이 None(꺼짐으로 지어내지 않음).
    구독 콜백(리더 스레드)에서 명령을 보내지 않는다 — 시작 상태 적용은
    별도 스레드.
  - 온보딩: 노드의 채널로 청사진을 채우고, 센서·스위치가 없는 쪽 하위는 만들지
    않는다. 대기 중인 노드는 스레드마다 따로 보인다.
"""
