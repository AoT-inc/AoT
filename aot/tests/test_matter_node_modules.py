def test_timed_on_keeps_its_auto_off_through_refresh(output_module):
    """600초 관수 ON 이 확정된 뒤 갱신 이벤트가 와도 자동 OFF 가 사라지지 않는다.
    예전에는 대기 중 갱신이 지속시간을 지워 밸브가 무기한 열려 있을 수 있었다."""
    module, client = output_module
    module.command_timeout_s = lambda ch=0: 0.5
    client._nodes[5]['attributes']['1/6/0'] = False
    module._on_event('connected', None)
    module.output_states[0] = False
    module.output_type = 'MATTER_ON_OFF'
    module.output_types = {'on_off': ['MATTER_ON_OFF'], 'pwm': [], 'value': [], 'volume': []}
    module.output_name = 'valve'
    code, _msg = module.output_on_off('on', output_channel=0, amount=600,
                                      trigger_conditionals=False)
    assert code == 0
    module._on_event('node_updated', client._nodes[5])     # refresh, stale cache (off)
    client._nodes[5]['attributes']['1/6/0'] = True
    module._on_event('attribute_updated', [5, '1/6/0', True])
    time.sleep(0.8)                                         # past the confirm window
    assert module.is_on(0) is True
    assert module.output_on_until.get(0) is not None        # auto-off still scheduled
    assert [s[1]['command_name'] for s in client.sent] == ['On']   # no fail-safe OFF
    assert not module.comm_is_fault(0)


