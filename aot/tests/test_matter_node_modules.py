# --- P3: 표본은 캐시가 아니라 장치에서 바로 읽는다 ----------------------------------

class _LiveReadClient(FakeClient):
    def __init__(self, nodes, live=None, fail=None):
        super().__init__(nodes)
        self.live = live or {}
        self.fail = fail

    def send_command(self, command, args=None, timeout=5.0):
        if command == 'read_attribute':
            self.sent.append((command, args, timeout))
            if self.fail is not None:
                raise self.fail
            return {p: self.live[p] for p in args['attribute_path'] if p in self.live}
        return super().send_command(command, args, timeout)


def test_sample_reads_live_values_not_the_cache(input_module):
    """다른 생태계가 AoT 의 Fabric 을 지워도 서버는 몇 분간 available 로 보인다
    (실측). 표본이 캐시를 쓰면 낡은 값이 새 값처럼 기록된다 — 그래서 장치에서
    바로 읽는다."""
    module, writes = input_module
    module.client = _LiveReadClient({7: _sensor_node(temp=2150, humid=4000)},
                                    live={'1/1026/0': 2400, '2/1029/0': 4100})
    module._write_snapshot('sample')
    command, args, timeout = module.client.sent[-1]
    assert command == 'read_attribute' and set(args['attribute_path']) == {'1/1026/0', '2/1029/0'}
    assert timeout <= 15
    assert writes[-1][0]['value'] == 24.0 and writes[-1][1]['value'] == 41.0


